// Tests du moteur : node tests/engine.test.mjs
import { Frac } from '../js/math/frac.js';
import { checkExpr, checkNumber, checkVars } from '../js/math/check.js';
import { reductionSteps, solveSteps, valueSteps } from '../js/math/steps.js';
let fail = 0;
const eq = (name, got, exp) => { if (got !== exp) { fail++; console.log('ÉCHEC', name, '→', got, 'attendu', exp); } };
eq('ordre', checkExpr('2 + 3x', '3x+2').status, 'correct');
eq('1x', checkExpr('1x+2', 'x+2').notes.length, 1);
eq('non réduit', checkExpr('3x+2x', '5x').status, 'nonreduit');
eq('parenthèses', checkExpr('2(x+1)', '2x+2').status, 'nonreduit');
eq('faux', checkExpr('3x+2', '3x-2').status, 'incorrect');
eq('invalide', checkExpr('3x+', '3x').status, 'invalid');
eq('X majuscule', checkExpr('3X', '3x').status, 'correct');
eq('x²', checkExpr('2x²-x', '2x^2-x').status, 'correct');
eq('signe −', checkExpr('−8a+12b', '-8a+12b').status, 'correct');
eq('nombre virgule', checkNumber('2,4', '2.4').status, 'correct');
eq('x=4', checkNumber('x = 4', 4).status, 'correct');
eq('fraction', checkNumber('7/3', new Frac(7, 3)).status, 'correct');
eq('approx', checkNumber('2,33', new Frac(7, 3)).status, 'correct');
eq('approx faux', checkNumber('2,3', new Frac(7, 3)).status, 'incorrect');
eq('vars', checkVars('x et y', 'xy').status, 'correct');
const r = reductionSteps('3x - (2x - 5)');
eq('réduction', r.poly.toLatex(), 'x + 5');
const s = solveSteps('3x+15x-3(x-2)', '42', 'x');
eq('solution', s.solution.toString(), '2,4');
const s2 = solveSteps('y/3-4', '5', 'y'); eq('x/a', s2.solution.toString(), '27');
const s3 = solveSteps('6x-7', '5x+9', 'x'); eq('2 côtés', s3.solution.toString(), '16');
const s4 = solveSteps('x/3-4+x/4', '31', 'x'); eq('fractions', s4.solution.toString(), '60');
const s5 = solveSteps('-10m', '12m-44', 'm'); eq('neg', s5.solution.toString(), '2');
const v = valueSteps('2x^2-3y+4', { x: -2, y: 5 }); eq('valeur', v.value.toString(), '-3');
for (const st of [...s.steps, ...v.steps, ...r.steps]) console.log('  ', st.label, '::', st.tex);
console.log(fail ? `${fail} échec(s)` : 'Tous les tests du moteur passent ✔');
process.exit(fail ? 1 : 0);
